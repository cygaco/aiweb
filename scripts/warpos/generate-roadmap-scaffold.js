#!/usr/bin/env node
/**
 * generate-roadmap-scaffold.js — writes a clean product-style ROADMAP.md
 * scaffold to the target project, but ONLY if no ROADMAP.md already exists.
 * Idempotent and non-destructive.
 *
 * Phase 0 workstream H. Invoked optionally by warp-setup.js for fresh
 * installs that want a starting roadmap file.
 *
 * Usage:
 *   node scripts/warpos/generate-roadmap-scaffold.js [<target-dir>]
 *
 * Exit codes:
 *   0 — wrote scaffold OR file already exists (no-op).
 *   2 — target dir missing.
 */

"use strict";

const fs = require("fs");
const path = require("path");

const target = path.resolve(process.argv[2] || process.cwd());
if (!fs.existsSync(target)) {
  process.stderr.write(`target directory does not exist: ${target}\n`);
  process.exit(2);
}

const dest = path.join(target, "ROADMAP.md");
if (fs.existsSync(dest)) {
  process.stdout.write(`ROADMAP.md exists at ${dest} — leaving it alone.\n`);
  process.exit(0);
}

const scaffold = [
  "# Roadmap",
  "",
  "## Current State",
  "",
  "_Describe where the project is today: what works, who can use it, what is in progress._",
  "",
  "## Active Backlog",
  "",
  "_Items the team is working on or about to start._",
  "",
  "## Next Milestones",
  "",
  "_Concrete release / launch markers with target dates._",
  "",
  "## Deferred",
  "",
  "_Things deliberately set aside until a named condition is met._",
  "",
  "## Notes",
  "",
  "_Open questions, risks, parking-lot items._",
  "",
  "---",
  "",
  "> Generated by WarpOS scripts/warpos/generate-roadmap-scaffold.js. WarpOS",
  "> will never overwrite this file — it's yours.",
  "",
].join("\n");

fs.writeFileSync(dest, scaffold);
process.stdout.write(`Wrote ${dest}\n`);
process.exit(0);
